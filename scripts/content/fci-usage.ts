/**
 * How often judges set each FCI card, counted over the competition courses of the FCI
 * Rally Obedience HUB's course catalogue (https://rallyobedience.online/courses/ — a public
 * Google Sheet of courses gathered from across the internet, one row per course with its
 * cards in order). Only the counts are kept; the courses themselves stay in the catalogue.
 *
 * Then the dealer's weights are calibrated against them, per field: deal courses, compare
 * how often each card comes with the judges' share, adjust, repeat. The field is what
 * needs it — a slalom or a leave card fits far less often than a turn.
 *
 *   bun run scripts/content/fci-usage.ts   → packages/content/src/fci/usage.ts
 *
 * Re-run when the catalogue has grown or the field planner changes (the test "competition
 * courses use cards like judges" says when), then `bun run format`.
 */
import { writeFile } from 'node:fs/promises'
import { dealDeck, EQUIPMENT, fieldKey, getClass, type Field } from '../../packages/content/src'
import { FCI_CARDS } from '../../packages/content/src/fci'

/** Courses dealt per calibration round, rounds per field. */
const COURSES = 300
const ROUNDS = 8
/** Weights stay within this factor of an even deal either way: nothing is ruled out. */
const SPREAD = 50

const SHEET =
  'https://docs.google.com/spreadsheets/d/1E2Ubzf4nOxxUMI2BIhRsF91coJy2XRXJY1HMITy1GOc/export?format=csv'
const OUT = 'packages/content/src/fci/usage.ts'

/** RFC 4180: quoted fields may hold commas, quotes ("") and line breaks. */
function parseCsv(text: string): string[][] {
  const rows: string[][] = []
  let row: string[] = []
  let field = ''
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c !== '"') field += c
      else if (text[i + 1] === '"') field += text[i++]
      else quoted = false
    } else if (c === '"') quoted = true
    else if (c === ',') {
      row.push(field)
      field = ''
    } else if (c === '\n') {
      rows.push([...row, field])
      row = []
      field = ''
    } else if (c !== '\r') field += c
  }
  if (field || row.length) rows.push([...row, field])
  return rows
}

async function main() {
  const response = await fetch(SHEET)
  if (!response.ok) throw new Error(`catalogue: HTTP ${response.status}`)
  const [head = [], ...rows] = parseCsv(await response.text())
  const column = (name: string) => {
    const i = head.findIndex((h) => h.trim().toLowerCase().startsWith(name))
    if (i < 0) throw new Error(`catalogue: no column "${name}" in ${head.join(' | ')}`)
    return i
  }
  const kind = column('kind')
  const stations = column('stations')
  const courses = rows
    .filter((r) => r[kind]?.trim() === 'c')
    .map((r) => (r[stations] ?? '').trim().split(/\s+/).filter(Boolean))
    .filter((cards) => cards.length > 0)

  const exercises = FCI_CARDS.filter((c) => c.kind === 'exercise').map((c) => c.code)
  const counts = new Map(exercises.map((code) => [code, 0]))
  const unknown = new Set<string>()
  for (const code of courses.flat()) {
    if (counts.has(code)) counts.set(code, (counts.get(code) ?? 0) + 1)
    else unknown.add(code)
  }
  if (unknown.size) console.warn(`unknown codes, left out: ${[...unknown].join(' ')}`)

  const total = [...counts.values()].reduce((sum, n) => sum + n, 0)
  const target = new Map(exercises.map((code) => [code, (counts.get(code) ?? 0) / total]))
  const cls = getClass('FCI-ROB')
  if (!cls?.course.fields) throw new Error('FCI-ROB has no fields')
  const weights: Record<string, Record<string, number>> = {}
  for (const field of cls.course.fields) {
    weights[fieldKey(field)] = calibrate(field, exercises, target)
  }

  const date = new Date().toISOString().slice(0, 10)
  const lines = exercises.map((code) => `    '${code}': ${counts.get(code)},`)
  const weightLines = Object.entries(weights).map(
    ([key, w]) =>
      `  '${key}': {\n${exercises.map((code) => `    '${code}': ${w[code]},`).join('\n')}\n  },`,
  )
  await writeFile(
    OUT,
    `// Generated by scripts/content/fci-usage.ts on ${date} — do not edit by hand.

/**
 * How often judges set each FCI card: times it appears on the ${courses.length} competition
 * courses of the FCI Rally Obedience HUB's course catalogue
 * (https://rallyobedience.online/courses/, ${date}).
 */
export const FCI_JUDGES_USAGE = {
  courses: ${courses.length},
  cards: {
${lines.join('\n')}
  } as Record<string, number>,
}

/**
 * The dealer's weight per card and field (\`course.dealWeights\`), calibrated so that
 * competition courses use each card about as often as \`FCI_JUDGES_USAGE\`.
 */
export const FCI_DEAL_WEIGHTS: Record<string, Record<string, number>> = {
${weightLines.join('\n')}
}
`,
  )
  console.log(`${courses.length} competition courses, ${total} cards → ${OUT}`)
}

/** Each card's share of the cards on `n` competition courses dealt on `field`. */
function dealtShares(field: Field, n: number, seed: number): Map<string, number> {
  const counts = new Map<string, number>()
  let total = 0
  for (let i = 0; i < n; i++) {
    const deck = dealDeck({
      classId: 'FCI-ROB',
      scope: 'all',
      count: 20,
      equipment: [...EQUIPMENT],
      startSide: i % 2 ? 'right' : 'left',
      seed: seed + i,
      competition: true,
      field,
    })
    for (const { code } of deck.entries) counts.set(code, (counts.get(code) ?? 0) + 1)
    total += deck.entries.length
  }
  return new Map([...counts].map(([code, c]) => [code, c / total]))
}

/** Half the summed difference of two shares: 0 = the same, 1 = nothing in common. */
const distance = (a: Map<string, number>, b: Map<string, number>) =>
  [...new Set([...a.keys(), ...b.keys()])].reduce(
    (sum, code) => sum + Math.abs((a.get(code) ?? 0) - (b.get(code) ?? 0)) / 2,
    0,
  )

function calibrate(field: Field, codes: string[], target: Map<string, number>) {
  const cls = getClass('FCI-ROB')
  if (!cls) throw new Error('no FCI-ROB')
  const floor = 0.2 / codes.length
  // Start from the judges' shares, relative to an even deal.
  let weights = new Map(codes.map((c) => [c, Math.max(floor, target.get(c) ?? 0) * codes.length]))
  const key = fieldKey(field)
  for (let round = 0; round <= ROUNDS; round++) {
    cls.course.dealWeights = { [key]: Object.fromEntries(weights) }
    const shares = dealtShares(field, COURSES, 1 + round * COURSES)
    console.log(`${key} round ${round}: ${distance(shares, target).toFixed(3)} from the judges`)
    if (round === ROUNDS) break
    // Most of the way to the factor that would match, damped against noise.
    const next = new Map(
      codes.map((c) => {
        const want = (target.get(c) ?? 0) + floor
        const have = (shares.get(c) ?? 0) + floor
        return [c, (weights.get(c) ?? 1) * Math.min(4, Math.max(0.25, (want / have) ** 0.7))]
      }),
    )
    // Geometric mean 1: an even deal stays the middle the lean starts from.
    const mean = Math.exp(codes.reduce((s, c) => s + Math.log(next.get(c) ?? 1), 0) / codes.length)
    weights = new Map(
      codes.map((c) => {
        const w = (next.get(c) ?? 1) / mean
        return [c, Math.min(SPREAD, Math.max(1 / SPREAD, w))]
      }),
    )
  }
  return Object.fromEntries(codes.map((c) => [c, Number((weights.get(c) ?? 1).toPrecision(3))]))
}

await main()
